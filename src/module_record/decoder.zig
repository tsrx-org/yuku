//! Prints src/module-record/layout.ts, the readers of the structs in layout.zig.

const std = @import("std");
const layout = @import("layout.zig");

pub fn main(init: std.process.Init) !void {
    var buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buffer);
    try generate(&stdout.interface);
    try stdout.interface.flush();
}

fn generate(w: *std.Io.Writer) !void {
    try w.writeAll("// generated by src/module_record/decoder.zig from src/module_record/layout.zig, do not edit\n");
    try w.writeAll("import type {");
    inline for (sorted, 0..) |name, i| try w.print("{s} {s}", .{ if (i == 0) "" else ",", name });
    try w.writeAll(" } from \"../module-record\";\n\n");
    try w.writeAll("export type Text = (start: number, end: number) => string;\n\n");
    try w.print("export const NONE = 0x{x};\n", .{layout.OptionalText.none.start});
    try w.print("export const POOL_BIT = 0x{x};\n", .{layout.Text.pool_bit});
    try indices(w, layout.Header, "HEADER");
    inline for (records) |record| try reader(w, record[0]);
}

// each struct with the type src/module-record.ts names it by, and its words constant
const records = .{
    .{ layout.StaticImport, "StaticImport", "STATIC_IMPORT" },
    .{ layout.StaticExport, "StaticExport", "STATIC_EXPORT" },
    .{ layout.Entry, "ExportEntry", "EXPORT_ENTRY" },
    .{ layout.DynamicImport, "DynamicImport", "DYNAMIC_IMPORT" },
};

const sorted = blk: {
    var list: [records.len][]const u8 = undefined;
    for (records, 0..) |record, i| list[i] = record[1];
    std.mem.sortUnstable([]const u8, &list, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);
    break :blk list;
};

fn names(comptime T: type) [2][]const u8 {
    inline for (records) |record| {
        if (record[0] == T) return .{ record[1], record[2] };
    }
    @compileError("no name for " ++ @typeName(T));
}

fn indices(w: *std.Io.Writer, comptime T: type, comptime name: []const u8) !void {
    try w.print("\nexport const {s} = {{\n", .{name});
    inline for (@typeInfo(T).@"struct".field_names) |field| {
        try w.print("  {f}: {d},\n", .{ camel(field), @offsetOf(T, field) / 4 });
    }
    try w.print("  words: {d},\n}} as const;\n", .{layout.words(T)});
}

fn reader(w: *std.Io.Writer, comptime T: type) !void {
    const info = @typeInfo(T).@"struct";
    const name, const words = names(T);
    try w.print("\nexport const {s}_WORDS = {d};\n\n", .{ words, layout.words(T) });
    try w.print("export function read{s}(u32: Uint32Array, i: number", .{name});
    inline for (info.field_types) |F| {
        if (F == layout.Text or F == layout.OptionalText) break try w.writeAll(", text: Text");
    }
    inline for (info.field_types) |F| {
        if (@typeInfo(F) == .@"enum" and @hasDecl(F, "Item")) {
            try w.print(", list: (count: number) => {s}[]", .{names(F.Item)[0]});
        }
    }
    try w.print("): {s} {{\n  return {{\n", .{name});
    inline for (info.field_names, info.field_types) |field, F| {
        const at = @offsetOf(T, field) / 4;
        try w.print("    {f}: ", .{camel(field)});
        if (F == layout.Offset or F == u32) {
            try w.print("u32[i + {d}]!", .{at});
        } else if (F == layout.Flag) {
            try w.print("u32[i + {d}] !== 0", .{at});
        } else if (F == layout.Text) {
            try w.print("text(u32[i + {d}]!, u32[i + {d}]!)", .{ at, at + 1 });
        } else if (F == layout.OptionalText) {
            try w.print("u32[i + {d}] === NONE ? null : text(u32[i + {d}]!, u32[i + {d}]!)", .{ at, at, at + 1 });
        } else if (@typeInfo(F) == .@"enum" and @hasDecl(F, "Item")) {
            try w.print("list(u32[i + {d}]!)", .{at});
        } else @compileError("no reader for " ++ @typeName(F));
        try w.writeAll(",\n");
    }
    try w.writeAll("  };\n}\n");
}

fn camel(comptime name: []const u8) Camel {
    return .{ .name = name };
}

const Camel = struct {
    name: []const u8,

    pub fn format(self: Camel, w: *std.Io.Writer) std.Io.Writer.Error!void {
        var upper = false;
        for (self.name) |c| {
            if (c == '_') {
                upper = true;
                continue;
            }
            try w.writeByte(if (upper) std.ascii.toUpper(c) else c);
            upper = false;
        }
    }
};
